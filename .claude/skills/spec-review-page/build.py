"""Assemble a spec review page: template + authored content + the spec's Markdown files.

Usage:
  python build.py <spec dir> <content.html> --ticket '#<n>' --title "..." --snapshot <hash> --date <yyyy-mm-dd> [--out <file>] [--no-delta]

The page is written to <spec dir>/review.html unless --out is given. An existing file is
overwritten only when it carries this skill's marker, so a hand-written review.html is never lost.

Every line of every Markdown file becomes an anchored span, so a citation such as
#spec-md-L142 jumps to spec.md line 142. The build fails when a citation has no anchor,
prints every cited line for checking, and prints the word count of the open sections.
"""

from __future__ import annotations

import argparse
import html
import pathlib
import re
import sys
from html.parser import HTMLParser

sys.stdout.reconfigure(encoding="utf-8")

HERE = pathlib.Path(__file__).parent
MARKER = "<!-- spec-review-page: generated by"


def slug(rel: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", rel.lower()).strip("-")


class CiteScan(HTMLParser):
    """Collect the fragment target of every <a> whose class list holds "cite".

    The parser, not a regex, reads the tag, so attribute order, quoting style and extra classes
    do not matter. A chip without a fragment href records "" and is reported as missing.
    """

    def __init__(self) -> None:
        super().__init__()
        self.targets: set[str] = set()

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        if tag != "a":
            return
        a = dict(attrs)
        if "cite" not in (a.get("class") or "").split():
            return
        href = a.get("href") or ""
        self.targets.add(href[1:] if href.startswith("#") else "")


def strip_details(text: str) -> str:
    """Remove every <details> element, nested ones included, so only open text remains."""
    kept = []
    depth = 0
    for part in re.split(r"(<details\b[^>]*>|</details>)", text):
        if part.startswith("<details"):
            depth += 1
        elif part == "</details>":
            depth = max(depth - 1, 0)
        elif depth == 0:
            kept.append(part)
    return " ".join(kept)


def previous_snapshot(path: pathlib.Path) -> str | None:
    """Return the snapshot hash of an existing generated page, or None."""
    if not path.exists():
        return None
    head = path.read_text(encoding="utf-8", errors="replace")[:4000]
    if MARKER not in head:
        return None
    m = re.search(r'name="spec-review-snapshot" content="([^"]*)"', head)
    return m.group(1) if m else ""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("spec_dir")
    ap.add_argument("content")
    ap.add_argument("--out", help="output file; default <spec dir>/review.html")
    ap.add_argument("--ticket", required=True)
    ap.add_argument("--title", required=True)
    ap.add_argument("--snapshot", required=True)
    ap.add_argument("--date", required=True)
    ap.add_argument("--no-delta", action="store_true", help="omit the 'what moved' nav entry")
    a = ap.parse_args()

    spec = pathlib.Path(a.spec_dir)
    files = sorted(p for p in spec.rglob("*.md"))
    if not files:
        print(f"no Markdown files under {spec}", file=sys.stderr)
        return 1

    out = pathlib.Path(a.out) if a.out else spec / "review.html"
    if out.exists() and previous_snapshot(out) is None:
        print(
            f"refusing to overwrite {out}: it was not generated by this skill. "
            "Move it away or pass --out.",
            file=sys.stderr,
        )
        return 1
    prev = previous_snapshot(out)
    if prev:
        print(f"previous page snapshot: {prev}   (start 'what moved' from here)")

    lines_by_slug: dict[str, list[str]] = {}
    blocks = []
    for p in files:
        rel = p.relative_to(spec).as_posix()
        s = slug(rel)
        if s in lines_by_slug:
            print(
                f"slug collision: two Markdown files map to '{s}'; rename one so every citation is unambiguous",
                file=sys.stderr,
            )
            return 1
        lines = p.read_text(encoding="utf-8").splitlines()
        lines_by_slug[s] = lines
        body = "".join(
            f'<span id="{s}-L{i}">{html.escape(l) or " "}</span>' for i, l in enumerate(lines, 1)
        )
        blocks.append(
            f'<details id="{s}"><summary>{html.escape(rel)} <span class="note">{len(lines)} lines</span></summary><pre>{body}</pre></details>'
        )

    content = pathlib.Path(a.content).read_text(encoding="utf-8")
    template = (HERE / "template.html").read_text(encoding="utf-8")
    page = (
        template.replace("{{TICKET}}", html.escape(a.ticket))
        .replace("{{TITLE}}", html.escape(a.title))
        .replace("{{SNAPSHOT}}", html.escape(a.snapshot))
        .replace("{{DATE}}", html.escape(a.date))
        .replace("{{FILE_COUNT}}", str(len(files)))
        .replace("{{NAV_DELTA}}", "" if a.no_delta else '<li><a href="#delta">What moved</a></li>')
        .replace("{{CONTENT}}", content)
        .replace("{{SOURCES}}", "\n".join(blocks))
    )

    # Scan the assembled page, not only the authored fragment, so links the template itself carries
    # are checked too. Every citation chip is collected first, then parsed, so a malformed target
    # such as "#spec_md-L1" is reported instead of silently ignored.
    scan = CiteScan()
    scan.feed(page)
    targets = sorted(scan.targets)
    cites = []
    missing = []
    for target in targets:
        m = re.fullmatch(r"([a-z0-9-]+)-L(\d+)", target)
        if m is None:
            missing.append(target)
            continue
        s, n = m.group(1), m.group(2)
        cites.append((s, n))
        if (
            s not in lines_by_slug
            or str(int(n)) != n  # "L01" never matches the generated "L1" anchor
            or int(n) < 1
            or int(n) > len(lines_by_slug[s])
        ):
            missing.append(f"{s}-L{n}")
    cites.sort(key=lambda c: (c[0], int(c[1])))

    print(f"files: {len(files)}   citations: {len(cites)}   missing anchors: {len(missing)}")
    for m in missing:
        print(f"  MISSING {m}")
    print()
    print("cited lines, check each against the claim it supports:")
    for s, n in cites:
        if f"{s}-L{n}" in missing:
            continue
        text = lines_by_slug[s][int(n) - 1].strip()
        print(f"  {s}:{int(n):>4}  {text}")

    open_only = strip_details(content)
    open_text = re.sub(r"<pre class=\"mermaid\">.*?</pre>", " ", open_only, flags=re.S)
    words = len(re.findall(r"\w+", re.sub(r"<[^>]+>", " ", open_text)))
    diagrams_open = len(re.findall(r"<pre class=\"mermaid\">", open_only))
    print()
    print(f"open-section words: {words}   (budget about 1800)")
    print(f"open diagrams: {diagrams_open}   (budget 3)")

    if missing:
        print("\nnot written: fix the missing anchors first", file=sys.stderr)
        return 1

    out.write_text(page, encoding="utf-8")
    print(f"\nwrote {out}  ({len(page.encode('utf-8')):,} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
