"""Assemble a spec review page: template + authored content + the spec's Markdown files.

Usage:
  python build.py <spec dir> <content.html> --ticket '#<n>' --title "..." --snapshot <hash> --date <yyyy-mm-dd> [--out <file>]

The nav shows "What moved" when the content has a <section id="delta">.

The page is written to <spec dir>/review.html unless --out is given. An existing file is
overwritten only when it carries this skill's marker, so a hand-written review.html is never lost.

Every line of every Markdown file becomes an anchored span, so a citation such as
#spec-md-L142 jumps to spec.md line 142. The build fails when a citation has no anchor,
prints every cited line for checking, and prints the word count of the open sections.
"""

from __future__ import annotations

import argparse
import html
import os
import pathlib
import re
import sys
import tempfile
from html.parser import HTMLParser

sys.stdout.reconfigure(encoding="utf-8")

HERE = pathlib.Path(__file__).parent
MARKER = "<!-- spec-review-page: generated by"


def slug(rel: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", rel.lower()).strip("-")


class CiteScan(HTMLParser):
    """Collect the fragment target of every <a> whose class list holds "cite".

    The parser, not a regex, reads the tag, so attribute order, quoting style and extra classes
    do not matter. A chip without a fragment href records "" and is reported as missing.
    """

    def __init__(self) -> None:
        super().__init__()
        self.targets: set[str] = set()

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        if tag != "a":
            return
        a = dict(attrs)
        if "cite" not in (a.get("class") or "").split():
            return
        href = a.get("href") or ""
        self.targets.add(href[1:] if href.startswith("#") else "")


class ContentScan(HTMLParser):
    """Read the authored fragment once: is there a delta section, and how many words and mermaid
    diagrams sit outside <details>. The parser handles case, quoting and comments, as CiteScan does.
    """

    def __init__(self) -> None:
        super().__init__()
        self.has_delta = False
        self.words = 0
        self.diagrams_open = 0
        self.details = 0
        self.in_mermaid = False

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        a = dict(attrs)
        if tag == "section" and a.get("id") == "delta":
            self.has_delta = True
        elif tag == "details":
            self.details += 1
        elif tag == "pre" and "mermaid" in (a.get("class") or "").split():
            self.in_mermaid = True
            if self.details == 0:
                self.diagrams_open += 1

    def handle_endtag(self, tag: str) -> None:
        if tag == "details":
            self.details = max(self.details - 1, 0)
        elif tag == "pre":
            self.in_mermaid = False

    def handle_data(self, data: str) -> None:
        if self.details == 0 and not self.in_mermaid:
            self.words += len(re.findall(r"\w+", data))


def previous_snapshot(path: pathlib.Path) -> str | None:
    """Return the snapshot hash of an existing generated page, or None."""
    if not path.exists():
        return None
    head = path.read_text(encoding="utf-8", errors="replace")[:4000]
    if MARKER not in head:
        return None
    m = re.search(r'name="spec-review-snapshot" content="([^"]*)"', head)
    return m.group(1) if m else ""


def read_utf8(path: pathlib.Path) -> str | None:
    """Return the file's text with LF line ends and no BOM, or None (after a message) when it is
    not UTF-8."""
    try:
        return path.read_bytes().decode("utf-8-sig").replace("\r\n", "\n").replace("\r", "\n")
    except UnicodeDecodeError as e:
        print(f"{path} is not UTF-8 ({e.reason} at byte {e.start}); save it as UTF-8", file=sys.stderr)
        return None


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("spec_dir")
    ap.add_argument("content")
    ap.add_argument("--out", help="output file; default <spec dir>/review.html")
    ap.add_argument("--ticket", required=True)
    ap.add_argument("--title", required=True)
    ap.add_argument("--snapshot", required=True)
    ap.add_argument("--date", required=True)
    a = ap.parse_args()

    spec = pathlib.Path(a.spec_dir)
    files = sorted(p for p in spec.rglob("*.md"))
    if not files:
        print(f"no Markdown files under {spec}", file=sys.stderr)
        return 1

    out = pathlib.Path(a.out) if a.out else spec / "review.html"
    prev = previous_snapshot(out)
    if out.exists() and prev is None:
        print(
            f"refusing to overwrite {out}: it was not generated by this skill. "
            "Move it away or pass --out.",
            file=sys.stderr,
        )
        return 1
    if prev:
        print(f"previous page snapshot: {prev}   (start 'what moved' from here)")

    lines_by_slug: dict[str, list[str]] = {}
    blocks = []
    for p in files:
        rel = p.relative_to(spec).as_posix()
        s = slug(rel)
        if s in lines_by_slug:
            print(
                f"slug collision: two Markdown files map to '{s}'; rename one so every citation is unambiguous",
                file=sys.stderr,
            )
            return 1
        text = read_utf8(p)
        if text is None:
            return 1
        # Split on "\n" only, as git and editors count lines; splitlines() also splits on \f and U+2028.
        lines = text.split("\n")
        if lines[-1] == "":
            lines.pop()
        lines_by_slug[s] = lines
        body = "".join(
            f'<span id="{s}-L{i}">{html.escape(l) or " "}</span>' for i, l in enumerate(lines, 1)
        )
        blocks.append(
            f'<details id="{s}"><summary>{html.escape(rel)} <span class="note">{len(lines)} lines</span></summary><pre>{body}</pre></details>'
        )

    content = read_utf8(pathlib.Path(a.content))
    template = read_utf8(HERE / "template.html")
    if content is None or template is None:
        return 1
    body = ContentScan()
    body.feed(content)
    body.close()
    has_delta = body.has_delta
    values = {
        "TICKET": html.escape(a.ticket),
        "TITLE": html.escape(a.title),
        "SNAPSHOT": html.escape(a.snapshot),
        "DATE": html.escape(a.date),
        "FILE_COUNT": str(len(files)),
        "NAV_DELTA": '<li><a href="#delta">What moved</a></li>' if has_delta else "",
        "CONTENT": content,
        "SOURCES": "\n".join(blocks),
    }
    # One pass over the template only, so a {{...}} inside the content or the sources stays text.
    page = re.sub(r"\{\{([A-Z_]+)\}\}", lambda m: values.get(m.group(1), m.group(0)), template)

    # Scan the assembled page, not only the authored fragment, so links the template itself carries
    # are checked too. Every citation chip is collected first, then parsed, so a malformed target
    # such as "#spec_md-L1" is reported instead of silently ignored.
    scan = CiteScan()
    scan.feed(page)
    targets = sorted(scan.targets)
    cites = []
    missing = []
    for target in targets:
        m = re.fullmatch(r"([a-z0-9-]+)-L(\d+)", target)
        if m is None:
            missing.append(target)
            continue
        s, n = m.group(1), m.group(2)
        cites.append((s, n))
        if (
            s not in lines_by_slug
            or str(int(n)) != n  # "L01" never matches the generated "L1" anchor
            or int(n) < 1
            or int(n) > len(lines_by_slug[s])
        ):
            missing.append(f"{s}-L{n}")
    cites.sort(key=lambda c: (c[0], int(c[1])))

    print(f"files: {len(files)}   citations: {len(cites)}   missing anchors: {len(missing)}")
    for m in missing:
        print(f"  MISSING {m}")
    print()
    print("cited lines, check each against the claim it supports:")
    for s, n in cites:
        if f"{s}-L{n}" in missing:
            continue
        text = lines_by_slug[s][int(n) - 1].strip()
        print(f"  {s}:{int(n):>4}  {text}")

    print()
    print(f"open-section words: {body.words}   (budget about 1800)")
    print(f"open diagrams: {body.diagrams_open}   (budget 3)")

    if missing:
        print("\nnot written: fix the missing anchors first", file=sys.stderr)
        return 1

    # A temp file of its own beside the target, then a rename: a failed write never leaves a
    # cut-off page with the marker, and two builds never share a temp file. Bytes keep LF on Windows.
    data = page.encode("utf-8")
    tmp = None
    try:
        fd, tmp = tempfile.mkstemp(prefix=f".{out.name}.", suffix=".tmp", dir=out.parent)
        with os.fdopen(fd, "wb") as f:
            f.write(data)
        os.replace(tmp, out)
    except OSError as e:
        if tmp is not None and os.path.exists(tmp):
            os.remove(tmp)
        print(f"not written: {out}: {e.strerror or e}", file=sys.stderr)
        return 1
    print(f"\nwrote {out}  ({len(data):,} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
